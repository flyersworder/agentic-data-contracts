"""Derive the *hollow* contract: arm C's scaffolding with its knowledge removed.

WHY THIS EXISTS. Arm `contract` differs from the two baselines in three ways at
once — it carries the manual's knowledge as a contract, it has nine governed
tools instead of raw SQL, and its prompt tells it to look things up before
writing SQL. The measured 2.4x gain over `manual_prompt` cannot be attributed
to the first of those while the other two ride along unmeasured, and "you also
told it to look things up" is the first objection any reader will raise.

`contract_hollow` holds the tools and the instruction fixed and removes only
the knowledge. Reading the two arms together:

  * hollow ~ schema_only  -> the contract's CONTENT is doing the work.
  * hollow ~ contract     -> the tool scaffolding is, and the headline claim
                             about contract-delivered context is wrong.

DERIVED, NOT AUTHORED. This module rewrites the frozen contract mechanically
rather than hand-writing a second one, because a hand-written control is a
second artifact whose differences nobody can enumerate. Here the difference IS
the diff: every field this module does not touch is byte-identical to the
contract under test, and `tests/test_hollow.py` asserts both halves — that the
structure matches exactly, and that the knowledge is gone.

WHAT COUNTS AS KNOWLEDGE. Anything a reader of `manual.md` or
`payments-readme.md` would recognise as a fact about payments: domain prose,
metric definitions (`sql_expression` above all — the fee formula lives there),
column descriptions, relationship descriptions. WHAT DOES NOT: names,
structure, types, table allow-lists, forbidden operations and rules. Those are
governance and shape, present in every arm's world one way or another, and
they are exactly what this control holds constant.

PROMPT LENGTH IS NOT HELD CONSTANT, DELIBERATELY. Padding the descriptions to
length with filler would keep the character count and introduce a different
confound — text that reads as content but carries none. The placeholders are
short and truthful, and the hollow arm's prompt is correspondingly smaller.
The variable under test is knowledge, not tokens.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

SOURCE_DIR = Path(__file__).parent.parent / "contract"
HOLLOW_DIR = Path(__file__).parent.parent / "contract_hollow"

NO_DOMAIN = "No documentation is available for this domain."
NO_SUMMARY = "No summary is available."
NO_METRIC = "No definition is available for this metric."


def _hollow_contract(raw: dict[str, Any]) -> dict[str, Any]:
    raw["name"] = f"{raw['name']}-hollow"
    for table in raw.get("semantic", {}).get("allowed_tables", []):
        if "description" in table:
            table["description"] = NO_SUMMARY
    for domain in raw.get("semantic", {}).get("domains", []):
        if "summary" in domain:
            domain["summary"] = NO_SUMMARY
        if "description" in domain:
            domain["description"] = NO_DOMAIN
    src = raw.get("semantic", {}).get("source", {})
    if src.get("path"):
        src["path"] = "./semantic.yml"
    return raw


def _hollow_semantic(raw: dict[str, Any]) -> dict[str, Any]:
    for metric in raw.get("metrics", []):
        if "description" in metric:
            metric["description"] = NO_METRIC
        # The fee formula lives here. This is the single most important
        # field to empty: leaving it would hand the hollow arm the exact
        # rule that drives the headline result.
        if "sql_expression" in metric:
            metric["sql_expression"] = ""
    for table in raw.get("tables", []):
        for column in table.get("columns", []):
            if "description" in column:
                column["description"] = ""
    for rel in raw.get("relationships", []):
        if "description" in rel:
            rel["description"] = NO_SUMMARY
    return raw


def build(source_dir: Path = SOURCE_DIR, out_dir: Path = HOLLOW_DIR) -> Path:
    """Write the hollow contract beside the real one. Idempotent."""
    out_dir.mkdir(parents=True, exist_ok=True)
    contract = yaml.safe_load((source_dir / "contract.yml").read_text())
    semantic = yaml.safe_load((source_dir / "semantic.yml").read_text())
    header = (
        "# GENERATED by dce/hollow.py from ../contract/ — do not edit by hand.\n"
        "# Arm C's scaffolding with its payments knowledge removed, so the\n"
        "# experiment can tell contract CONTENT apart from contract TOOLING.\n"
    )
    (out_dir / "contract.yml").write_text(
        header + yaml.safe_dump(_hollow_contract(contract), sort_keys=False)
    )
    (out_dir / "semantic.yml").write_text(
        header + yaml.safe_dump(_hollow_semantic(semantic), sort_keys=False)
    )
    return out_dir


if __name__ == "__main__":
    print(build())
